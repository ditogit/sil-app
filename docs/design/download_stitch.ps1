$baseDir = "e:\www\sil-app\docs"

foreach ($s in $screens) {
    Write-Host "Downloading $($s.title)..."
    $htmlPath = Join-Path $baseDir "$($s.name).html"
    $imgPath = Join-Path $baseDir "screenshots\$($s.name).png"

    try {
        Invoke-WebRequest -Uri $s.htmlUrl -OutFile $htmlPath
        Write-Host "  [OK] HTML saved to $htmlPath"
    } catch {
        Write-Host "  [FAIL] HTML for $($s.name): $_"
    }

    try {
        Invoke-WebRequest -Uri $s.imgUrl -OutFile $imgPath
        Write-Host "  [OK] Screenshot saved to $imgPath"
    } catch {
        Write-Host "  [FAIL] Screenshot for $($s.name): $_"
    }
}

Write-Host "Download complete!"
